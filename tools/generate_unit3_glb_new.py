# ----------------------------------------------------------------- primitives
def _emit(mesh, material, name):
    """un-merge, add planar UVs (world-space metres) and register the mesh."""
    mesh.unmerge_vertices()
    tri = mesh.vertices[mesh.faces]
    fn = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
    fn /= (np.linalg.norm(fn, axis=1, keepdims=True) + 1e-12)
    n = np.abs(np.repeat(fn, 3, axis=0))            # faces are ordered 3 verts each
    v = mesh.vertices
    uv = np.where((n[:, 1:2] >= n[:, 0:1]) & (n[:, 1:2] >= n[:, 2:3]), v[:, [0, 2]],
                  np.where(n[:, 0:1] >= n[:, 2:3], v[:, [2, 1]], v[:, [0, 1]]))
    mesh.visual = trimesh.visual.TextureVisuals(uv=uv.astype(np.float32), material=material)
    k = _used.get(name, 0)
    _used[name] = k + 1
    PARTS.append((mesh, name if k == 0 else f"{name}_{k}"))


def box(name, material, x0, x1, y0, y1, z0, z1):
    sx, sy, sz = x1 - x0, y1 - y0, z1 - z0
    if min(sx, sy, sz) <= 1e-6:
        raise ValueError(f"degenerate box {name}: {sx:.4f},{sy:.4f},{sz:.4f}")
    m = trimesh.creation.box(extents=[sx, sy, sz])
    m.apply_translation([(x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2])
    _emit(m, material, name)


def bx(axis, name, material, a0, a1, y0, y1, c0, c1):
    """box where (a0,a1) run along `axis` ('x' or 'z') and (c0,c1) is the cross direction."""
    if axis == "x":
        box(name, material, a0, a1, y0, y1, c0, c1)
    else:
        box(name, material, c0, c1, y0, y1, a0, a1)


def cyl(name, material, cx, cy, cz, r, h, axis="y", sections=32, scale=(1, 1, 1)):
    """cylinder centred at (cx,cy,cz). axis = direction of its length (trimesh default is Z)."""
    m = trimesh.creation.cylinder(radius=r, height=h, sections=sections)
    if axis == "y":
        m.apply_transform(trimesh.transformations.rotation_matrix(np.pi / 2, [1, 0, 0]))
    elif axis == "x":
        m.apply_transform(trimesh.transformations.rotation_matrix(np.pi / 2, [0, 1, 0]))
    m.apply_scale(scale)
    m.apply_translation([cx, cy, cz])
    _emit(m, material, name)


def ball(name, material, cx, cy, cz, r, sy=1.0):
    m = trimesh.creation.icosphere(subdivisions=2, radius=r)
    m.apply_scale([1, sy, 1])
    m.apply_translation([cx, cy, cz])
    _emit(m, material, name)


def ceiling_quad(name, x0, x1, z0, z1, y=H_WALL):
    """single-sided quad whose normal faces DOWN (seen from inside, culled from above)."""
    v = np.array([[x0, y, z0], [x1, y, z0], [x1, y, z1], [x0, y, z1]], dtype=float)
    m = trimesh.Trimesh(vertices=v, faces=[[0, 1, 2], [0, 2, 3]], process=False)
    _emit(m, M["ceiling"], name)


# ----------------------------------------------------------------- architecture helpers
def wall_run(name, material, axis, a0, a1, c0, c1, openings=(), y0=-FT, y1=H_WALL):
    """Wall along `axis` from a0..a1, thickness c0..c1.
    openings = [(start, end, sill_height, head_height)] -> piers, sill piece, lintel piece."""
    def put(tag, s, e, ya, yb):
        if e - s > 1e-6 and yb - ya > 1e-6:
            bx(axis, f"{name}_{tag}", material, s, e, ya, yb, c0, c1)
    cur = a0
    for k, (s, e, sill, head) in enumerate(sorted(openings)):
        put(f"pier{k}", cur, s, y0, y1)
        put(f"sill{k}", s, e, y0, sill)
        put(f"lintel{k}", s, e, head, y1)
        cur = e
    put(f"pier{len(openings)}", cur, a1, y0, y1)


def door(name, axis, wc0, wc1, a0, a1, hinge_at_end=True):
    """Closed door: frame (jambs+head) sits INSIDE the structural opening a0..a1, leaf fills it.
    Leaf width = (a1-a0) - 2*0.04 frame."""
    fb, c = 0.04, (wc0 + wc1) / 2
    f0, f1 = wc0 - 0.012, wc1 + 0.012
    bx(axis, f"{name}_JambA", M["skirt"], a0, a0 + fb, 0, H_DOOR, f0, f1)
    bx(axis, f"{name}_JambB", M["skirt"], a1 - fb, a1, 0, H_DOOR, f0, f1)
    bx(axis, f"{name}_Head", M["skirt"], a0 + fb, a1 - fb, H_DOOR - fb, H_DOOR, f0, f1)
    la0, la1 = a0 + fb, a1 - fb
    bx(axis, f"{name}_Leaf", M["door"], la0, la1, 0.010, H_DOOR - fb, c - 0.02, c + 0.02)
    hx = (la0 + 0.07) if hinge_at_end else (la1 - 0.07)
    for side in (-1, 1):
        face = c + side * 0.02
        lo, hi = sorted((face, face + side * 0.006))
        bx(axis, f"{name}_Rose{side}", M["brass"], hx - 0.02, hx + 0.02, 0.96, 1.12, lo, hi)
        lo, hi = sorted((face + side * 0.006, face + side * 0.040))
        bx(axis, f"{name}_Stem{side}", M["brass"], hx - 0.008, hx + 0.008, 1.03, 1.05, lo, hi)
        lo, hi = sorted((face + side * 0.030, face + side * 0.042))
        d = -1 if hinge_at_end else 1
        s0, s1 = sorted((hx - 0.008, hx - 0.008 + d * 0.12))
        bx(axis, f"{name}_Lever{side}", M["brass"], s0, s1, 1.03, 1.05, lo, hi)


def glazed_x(prefix, xc, z0, z1, y0, y1, sashes=2, depth=0.07, bar=0.05):
    """Window / sliding door in a wall whose thickness runs along X. Fills opening z0..z1, y0..y1."""
    h = depth / 2
    box(prefix + "_FrmL", M["black"], xc - h, xc + h, y0, y1, z0, z0 + bar)
    box(prefix + "_FrmR", M["black"], xc - h, xc + h, y0, y1, z1 - bar, z1)
    box(prefix + "_FrmT", M["black"], xc - h, xc + h, y1 - bar, y1, z0 + bar, z1 - bar)
    box(prefix + "_FrmB", M["black"], xc - h, xc + h, y0, y0 + bar, z0 + bar, z1 - bar)
    iz0, iz1, iy0, iy1 = z0 + bar, z1 - bar, y0 + bar, y1 - bar
    if sashes == 1:
        box(prefix + "_Glass", M["glass"], xc - 0.006, xc + 0.006, iy0, iy1, iz0, iz1)
        return
    w, sb, tx = (iz1 - iz0) / sashes, 0.04, 0.014
    for i in range(sashes):
        xo = xc + (i - (sashes - 1) / 2) * 0.034
        s0 = iz0 + i * w - (0.02 if i > 0 else 0)
        s1 = iz0 + (i + 1) * w + (0.02 if i < sashes - 1 else 0)
        p = f"{prefix}_S{i}"
        box(p + "_L", M["black"], xo - tx, xo + tx, iy0, iy1, s0, s0 + sb)
        box(p + "_R", M["black"], xo - tx, xo + tx, iy0, iy1, s1 - sb, s1)
        box(p + "_T", M["black"], xo - tx, xo + tx, iy1 - sb, iy1, s0 + sb, s1 - sb)
        box(p + "_B", M["black"], xo - tx, xo + tx, iy0, iy0 + sb, s0 + sb, s1 - sb)
        box(p + "_Glass", M["glass"], xo - 0.005, xo + 0.005, iy0 + sb, iy1 - sb, s0 + sb, s1 - sb)


def skirt(name, axis, a0, a1, face, side):
    """skirting 90 mm x 12 mm on a wall face. side=+1 -> projects toward +c."""
    lo, hi = sorted((face, face + side * 0.012))
    bx(axis, name, M["skirt"], a0, a1, 0, 0.09, lo, hi)


def fronts(prefix, fmat, fx0, fx1, out, za, zb, y0, y1, n, mode, hy=None, gap=0.004):
    """cabinet fronts (+brass handles). out=-1: face toward -X, +1: toward +X."""
    hx = (fx0 - 0.03, fx0) if out < 0 else (fx1, fx1 + 0.03)
    if mode == "drawers":
        h = (y1 - y0) / n
        for i in range(n):
            ya, yb = y0 + i * h + gap / 2, y0 + (i + 1) * h - gap / 2
            box(f"{prefix}_Dr{i}", fmat, fx0, fx1, ya, yb, za + gap / 2, zb - gap / 2)
            zc, yc = (za + zb) / 2, yb - 0.045
            box(f"{prefix}_DrH{i}", M["brass"], hx[0], hx[1], yc - 0.006, yc + 0.006, zc - 0.13, zc + 0.13)
    else:
        w = (zb - za) / n
        hy = hy or (y1 - 0.32, y1 - 0.06)
        for i in range(n):
            a, b = za + i * w + gap / 2, za + (i + 1) * w - gap / 2
            box(f"{prefix}_Door{i}", fmat, fx0, fx1, y0, y1, a, b)
            zh = (a + 0.05) if i % 2 else (b - 0.05)
            box(f"{prefix}_DoorH{i}", M["brass"], hx[0], hx[1], hy[0], hy[1], zh - 0.006, zh + 0.006)


