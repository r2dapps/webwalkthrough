def run(out_path, ground=False, ceiling=True):
    build_shell(ceiling)
    build_living()
    build_bedroom()
    build_kitchen()
    build_toilet()
    build_balcony()
    if ground:
        box("Ground", M["ground"], -12, 25, -3.35, -3.15, -12, 18)

    scene = trimesh.Scene()
    for mesh, name in PARTS:
        scene.add_geometry(mesh, node_name=name, geom_name=name)
    glb = trimesh.exchange.gltf.export_glb(scene)
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "wb") as f:
        f.write(glb)
    b = scene.bounds
    print(f"Wrote {out_path}")
    print(f"  nodes: {len(PARTS)}   size: {len(glb)/1024:.1f} KB")
    print(f"  bounds X {b[0][0]:.2f}..{b[1][0]:.2f}  Y {b[0][1]:.2f}..{b[1][1]:.2f}  Z {b[0][2]:.2f}..{b[1][2]:.2f}")


